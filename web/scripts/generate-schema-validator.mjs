import { readFile, writeFile } from "node:fs/promises";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import { _ } from "ajv/dist/compile/codegen/index.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const schemaUrl = new URL("../src/schema/planning_optimizer_schema_v1.json", import.meta.url);
const outputUrl = new URL("../src/schema/planning_optimizer_schema_v1.validator.generated.ts", import.meta.url);
const schema = JSON.parse(await readFile(schemaUrl, "utf8"));
const browserFormats = _`(() => {
  const datePattern = /^(\\d{4})-(\\d{2})-(\\d{2})$/;
  const timePattern = /^(\\d{2}):(\\d{2}):(\\d{2}(?:\\.\\d+)?)(z|([+-])(\\d{2})(?::?(\\d{2}))?)$/i;
  const isLeapYear = (year) => year % 4 === 0 && (year % 100 !== 0 || year % 400 === 0);
  const monthDays = [0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
  const date = (value) => {
    const match = datePattern.exec(value);
    if (!match) return false;
    const year = Number(match[1]);
    const month = Number(match[2]);
    const day = Number(match[3]);
    return month >= 1 && month <= 12 && day >= 1 && day <= (month === 2 && isLeapYear(year) ? 29 : monthDays[month]);
  };
  const time = (value) => {
    const match = timePattern.exec(value);
    if (!match) return false;
    const hour = Number(match[1]);
    const minute = Number(match[2]);
    const second = Number(match[3]);
    const offsetSign = match[5] === "-" ? -1 : 1;
    const offsetHour = Number(match[6] || 0);
    const offsetMinute = Number(match[7] || 0);
    if (offsetHour > 23 || offsetMinute > 59) return false;
    if (hour <= 23 && minute <= 59 && second < 60) return true;
    const utcMinute = minute - offsetMinute * offsetSign;
    const utcHour = hour - offsetHour * offsetSign - (utcMinute < 0 ? 1 : 0);
    return (utcHour === 23 || utcHour === -1) && (utcMinute === 59 || utcMinute === -1) && second < 61;
  };
  const dateTime = (value) => {
    const parts = value.split(/t|\\s/i);
    return parts.length === 2 && date(parts[0]) && time(parts[1]);
  };
  return { date: { validate: date }, "date-time": { validate: dateTime } };
})()`;

const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  code: { source: true, esm: true, optimize: true, formats: browserFormats },
});
addFormats(ajv, ["date", "date-time"]);

const validate = ajv.compile(schema);
const source = standaloneCode(ajv, validate);
const banner = `// @ts-nocheck
// Generated by scripts/generate-schema-validator.mjs. Do not edit manually.
// AJV is compiled at build time so the browser does not require unsafe-eval.
`;

await writeFile(outputUrl, `${banner}${source}\n`, "utf8");
